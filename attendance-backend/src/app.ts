import "dotenv/config";
import cors from "cors";
import express from "express";
import { attendanceRouter } from "./routes/attendance.js";
import { dashboardRouter } from "./routes/dashboard.js";
import { peopleRouter } from "./routes/people.js";
import { reportsRouter } from "./routes/reports.js";
import { settingsRouter } from "./routes/settings.js";
import { workspacesRouter } from "./routes/workspaces.js";
export const app = express();
app.use(cors({ origin: process.env.WEB_ORIGIN ?? "http://localhost:3000" }));
app.use(express.json({ limit: "1mb" }));
app.get("/api/health", (_request, response) => response.json({ ok: true, service: "attendance-api" }));
app.use("/api/workspaces", workspacesRouter);
app.use("/api/dashboard", dashboardRouter);
app.use("/api/people", peopleRouter);
app.use("/api/attendance", attendanceRouter);
app.use("/api/reports", reportsRouter);
app.use("/api/settings", settingsRouter);
app.use((error: unknown, _request: express.Request, response: express.Response, _next: express.NextFunction) => { console.error(error); response.status(500).json({ message: "Unexpected server error" }); });
